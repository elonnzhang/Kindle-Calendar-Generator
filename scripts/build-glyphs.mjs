// Regenerates src/lib/glyphs.js: outlines for every character the calendar
// cover draws. Text on the cover is drawn as paths, so the cover looks the
// same in the browser and on a Kindle, which has none of these fonts.
//
// usage: node scripts/build-glyphs.mjs
import opentype from 'opentype.js';
import fs from 'node:fs';

const CJK = '一二三四五六七八九十日月年';
const DIGITS = '0123456789';
const CAPS = [...new Set('JANUARYFEBRUARYMARCHAPRILMAYJUNEJULYAUGUSTSEPTEMBEROCTOBERNOVEMBERDECEMBERH')].sort().join('');

const FACES = {
  display: { family: 'Bodoni Moda', axes: 'opsz,wght@96,500', text: DIGITS, ref: '0' },
  numeral: { family: 'Bodoni Moda', axes: 'opsz,wght@11,500', text: DIGITS, ref: '0' },
  caps: { family: 'Bodoni Moda', axes: 'opsz,wght@11,500', text: CAPS, ref: 'H' },
  cjkBold: { family: 'Noto Serif SC', axes: 'wght@700', text: CJK, ref: '日' },
};

async function fetchSubset({ family, axes, text }) {
  const css = await fetch(
    `https://fonts.googleapis.com/css2?family=${family.replaceAll(' ', '+')}:${axes}&text=${encodeURIComponent(text)}`,
  ).then((r) => r.text());
  const url = css.match(/url\((https:[^)]+)\)/)?.[1];
  if (!url) throw new Error(`No font URL for ${family} ${axes}:\n${css}`);
  return fetch(url).then((r) => r.arrayBuffer());
}

const round = (n) => Math.round(n);
const out = {};
for (const [name, face] of Object.entries(FACES)) {
  const font = opentype.parse(await fetchSubset(face));
  const em = font.unitsPerEm;
  const glyphs = {};
  for (const ch of face.text) {
    const g = font.charToGlyph(ch);
    if (!g || g.index === 0) throw new Error(`${face.family} has no glyph for ${ch}`);
    glyphs[ch] = { w: round(g.advanceWidth), d: g.getPath(0, 0, em).toPathData(0) };
  }
  // Height of the reference glyph above the baseline, for vertical centring.
  const height = round(-font.charToGlyph(face.ref).getPath(0, 0, em).getBoundingBox().y1);
  out[name] = { em, height, glyphs };
  console.log(`${name}: ${face.family} ${face.axes}, ${face.text.length} glyphs`);
}

const header = `// Generated by scripts/build-glyphs.mjs. Do not edit.
// Outlines from Bodoni Moda (Owen Earl) and Noto Serif SC (Google),
// both under the SIL Open Font License 1.1: https://openfontlicense.org
`;
fs.writeFileSync(new URL('../src/lib/glyphs.js', import.meta.url), `${header}export const FONTS = ${JSON.stringify(out)};\n`);
